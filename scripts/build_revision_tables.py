#!/usr/bin/env python3
"""Build S14--S17 from packaged saved summaries and frozen cell labels.

Python standard library only. No home-directory fallback, fitting, gene-score
calculation, new annotation, or membership changes. Counts, pooled weights and
arithmetic combinations of saved means are the only derived numerical fields.
Run: python scripts/build_revision_tables.py [--input-root PACKAGE]
     [--output-root OUTPUT] [--check]
The output root receives supplement_tables/ and evidence/. --check compares
generated bytes with existing outputs without modifying them.
"""
import argparse
from collections import Counter, defaultdict
import csv
import gzip
import hashlib
import io
import json
import math
from pathlib import Path

COHORTS = ("ucb", "dapp1", "sleep")
LABEL = {"ucb": "TPO", "dapp1": "Dapp1", "sleep": "Sleep", "marrow": "Marrow"}
ORDER = {"ucb": ("D0", "D4", "D7", "D11", "D14"), "dapp1": ("wt", "ko"),
         "sleep": ("CT", "SD"), "marrow": ("HSC", "MPP", "MLP", "PreBNK", "MEP", "CMP", "GMP")}
BASE = Path("source_data/results/application_reanalysis_20260921")
EXTRA = Path("revision_data/annotation")
# Declared before replay: saved cluster means have float32 display precision;
# within-group tables and standardized contrasts have float64 precision.
POOLED_MEAN_ABS_TOL = 2e-6
CONTRAST_ABS_TOL = 1e-10


def sha(data):
    return hashlib.sha256(data).hexdigest()


def f(value, digits=3):
    return "--" if value == "" else f"{float(value):.{digits}f}"


def esc(value):
    mapping = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$"}
    return "".join(mapping.get(c, c) for c in str(value))


def pname(key):
    return key.removeprefix("program_").replace("neutrophil", "granulocytic").replace("megakaryocyte", "Mk").replace("_", " ")


def top(row, keys):
    return sorted((k for k in keys if row.get(k, "") != ""), key=lambda k: float(row[k]), reverse=True)


class Build:
    def __init__(self, root):
        self.root = root
        self.sources = {}
        self.outputs = {}
        self.checks = []

    def data(self, path):
        path = Path(path)
        data = (self.root / path).read_bytes()
        self.sources[str(path)] = sha(data)
        return data

    def js(self, path):
        return json.loads(self.data(path))

    def csv(self, path):
        data = self.data(path)
        if str(path).endswith(".gz"):
            data = gzip.decompress(data)
        return list(csv.DictReader(io.StringIO(data.decode())))

    def saved(self, cohort, filename):
        path = BASE / cohort / filename
        if not (self.root / path).exists():
            path = EXTRA / cohort / filename
        return self.csv(path)

    def out_csv(self, name, rows):
        assert rows, name
        stream = io.StringIO(newline="")
        fields = list(dict.fromkeys(k for row in rows for k in row))
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
        self.outputs["supplement_tables/" + name + ".csv"] = stream.getvalue().encode()

    def table(self, name, caption, headers, widths, rows):
        assert len(headers) == len(widths)
        # At most 93% of text width; the rest accommodates inter-column glue.
        assert sum(widths) <= .931
        columns = "@{}" + "".join(r">{\raggedright\arraybackslash}p{" + str(w) + r"\linewidth}" for w in widths) + "@{}"
        header = " & ".join(headers) + r" \\"
        lines = [r"\begingroup", r"\small", r"\setlength{\tabcolsep}{2.5pt}",
                 r"\renewcommand{\arraystretch}{1.13}", r"\begin{longtable}{" + columns + "}",
                 r"\caption{" + caption + r"}\label{tab:" + name + r"}\\", r"\toprule", header,
                 r"\midrule", r"\endfirsthead", r"\multicolumn{" + str(len(headers)) + r"}{l}{\small\tablename\ \thetable\ continued}\\",
                 r"\toprule", header, r"\midrule", r"\endhead", r"\midrule",
                 r"\multicolumn{" + str(len(headers)) + r"}{r}{\small Continued on next page}\\",
                 r"\endfoot", r"\bottomrule", r"\endlastfoot"]
        for row in rows:
            assert len(row) == len(headers)
            lines.append(" & ".join(esc(v) for v in row) + r" \\")
        lines += [r"\end{longtable}", r"\endgroup", ""]
        self.outputs["supplement_tables/" + name + ".tex"] = "\n".join(lines).encode()

    def run(self):
        manifest = self.js(EXTRA / "input_manifest.json")
        for item in manifest["files"]:
            assert sha(self.data(item["path"])) == item["sha256"], item["path"]
        records = self.js(EXTRA / "annotation_records.json")
        self.checks.append({"name": "packaged_annotation_input_hashes", "files": len(manifest["files"]), "passed": True})
        protocols = {c: self.js(BASE / c / "protocol.json") for c in (*COHORTS, "marrow")}
        counts, means, clusters, labels, lineage_keys = {}, {}, {}, {}, {}
        marker_means, marker_detection = {}, {}
        for c in (*COHORTS, "marrow"):
            counts[c] = {r["condition"]: {k: int(v) for k, v in r.items() if k != "condition"} for r in self.saved(c, "composition_counts.csv")}
            key = "cell_type" if c == "marrow" else "leiden"
            means[c] = {(r["condition"], r[key]): r for r in self.saved(c, "within_group_program_means.csv")}
            clusters[c] = {r["leiden"]: r for r in self.saved(c, "cluster_programs.csv")}
            lineage_keys[c] = [k for k in next(iter(clusters[c].values())) if k.startswith("program_")]
            metadata = self.csv(EXTRA / c / "cell_labels.csv.gz")
            assert len(metadata) == protocols[c]["n_cells"]
            assert len({r["cell_id"] for r in metadata}) == len(metadata)
            observed_counts = Counter((r["condition"], r[key]) for r in metadata)
            for condition, groups in counts[c].items():
                assert sum(groups.values()) == protocols[c]["conditions"][condition]
                for group, n in groups.items():
                    assert observed_counts[condition, group] == n, (c, condition, group)
                    assert ((condition, group) in means[c]) == (n > 0)
            assert sum(observed_counts.values()) == sum(sum(x.values()) for x in counts[c].values())
            labels[c] = {}
            for r in metadata:
                group = r[key]
                labels[c].setdefault(group, set()).add(r["cell_type"])
                winner = top(clusters[c][r["leiden"]], lineage_keys[c])[0].removeprefix("program_")
                assert r["program_annotation"] == winner
                if c != "marrow":
                    assert r["cell_type"] == winner
                else:
                    assert r["cell_type"] == r["condition"] and r["donor"] == "A"
            assert all(len(v) == 1 for v in labels[c].values())
            labels[c] = {k: next(iter(v)) for k, v in labels[c].items()}
            for source, target in [("within_group_gene_means.csv", marker_means), ("within_group_gene_detection.csv", marker_detection)]:
                target[c] = {(r["condition"], r[key]): r for r in self.saved(c, source)}
                assert set(target[c]) == set(means[c])
            self.checks.append({"name": "frozen_cell_count_label_and_group_coverage", "cohort": c,
                                "cells": len(metadata), "groups": len(labels[c]), "passed": True})

        s14, display, contrasts = [], [], []
        for c in ("dapp1", "sleep"):
            a, b = ORDER[c]
            groups = sorted(counts[c][a], key=int)
            eligible = [g for g in groups if counts[c][a][g] >= 20 and counts[c][b][g] >= 20]
            assert eligible == groups and len(groups) == (11 if c == "dapp1" else 19)
            denominator = sum(counts[c][a][g] + counts[c][b][g] for g in eligible)
            coverage = denominator / protocols[c]["n_cells"]
            saved = {r["program"]: r for r in self.saved(c, "composition_standardized_effects.csv")}
            for program in (["program_neutrophil", "program_cycling"] if c == "dapp1" else ["program_neutrophil"]):
                pieces = []
                for g in eligible:
                    na, nb = counts[c][a][g], counts[c][b][g]
                    ma, mb = means[c][a, g][program], means[c][b, g][program]
                    weight = (na + nb) / denominator
                    delta = float(mb) - float(ma)
                    row = {"cohort": c, "cluster": g, "pooled_program_label": labels[c][g], "program": program,
                           "condition_a": a, "condition_b": b, "n_a": na, "n_b": nb,
                           "saved_mean_a": ma, "saved_mean_b": mb, "eligible_minimum_per_condition": 20,
                           "pooled_weight_numerator": na + nb, "pooled_weight_denominator": denominator,
                           "pooled_weight": weight, "mean_difference_b_minus_a": delta,
                           "weighted_difference": weight * delta, "eligible_groups": len(eligible),
                           "fraction_cells_covered": coverage, "saved_fixed_contrast": saved[program]["composition_standardized_delta"],
                           "saved_raw_contrast": saved[program]["unadjusted_delta"]}
                    s14.append(row); pieces.append(row)
                    display.append([LABEL[c] + " / " + ("cycle" if program == "program_cycling" else "gran."), g,
                                    f"{na:,} / {nb:,}", f(weight, 4), f(ma), f(mb), f(delta), f(weight * delta, 4)])
                fixed = math.fsum(x["weighted_difference"] for x in pieces)
                assert math.isclose(fixed, float(saved[program]["composition_standardized_delta"]), rel_tol=0, abs_tol=CONTRAST_ABS_TOL)
                assert math.isclose(math.fsum(x["pooled_weight"] for x in pieces), 1, rel_tol=0, abs_tol=1e-14)
                assert int(saved[program]["matched_groups"]) == len(eligible)
                assert float(saved[program]["fraction_cells_covered"]) == coverage == 1
                contrasts.append({"cohort": c, "program": program, "recombined_saved_means": fixed,
                                  "saved_fixed_contrast": float(saved[program]["composition_standardized_delta"]),
                                  "absolute_difference": abs(fixed-float(saved[program]["composition_standardized_delta"])),
                                  "largest_absolute_weighted_entries": [{k: r[k] for k in ["cluster", "pooled_weight", "mean_difference_b_minus_a", "weighted_difference"]} for r in sorted(pieces, key=lambda r: abs(r["weighted_difference"]), reverse=True)[:3]]})
        assert len(s14) == 41
        self.out_csv("s14_group_contrasts", s14)
        self.table("s14_group_contrasts", "Every eligible frozen cluster underlying the headline fixed-composition contrasts. Gran. is the granulocytic program; cycle is the cell-cycle program. A/B denotes WT/KO for Dapp1 and CT/SD for sleep. All 11 Dapp1 and 19 sleep groups have at least 20 cells in each condition, covering 100\\% of retained cells. The pooled weight is $(n_A+n_B)/\\sum_g(n_{Ag}+n_{Bg})$; the last column is its product with the saved within-group mean difference. These arithmetic contributions describe the saved standardized expression contrast, not a causal decomposition of model values. Exact saved means, count numerators/denominators and unrounded arithmetic are in the CSV.",
                   ["Cohort / program", "Group", "$n_A$ / $n_B$", "Weight", "Mean A", "Mean B", "$B-A$", "Weighted $B-A$"],
                   [.16, .06, .17, .10, .10, .10, .10, .13], display)

        s15, display = [], []
        for g in sorted(clusters["ucb"], key=int):
            pooled = clusters["ucb"][g]
            d0 = means["ucb"].get(("D0", g), {})
            row = {"cohort": "ucb", "cluster": g, "pooled_program_label": labels["ucb"][g],
                   **{"n_"+d: counts["ucb"][d][g] for d in ORDER["ucb"]},
                   "n_pooled": sum(counts["ucb"][d][g] for d in ORDER["ucb"]), "D0_denominator": protocols["ucb"]["conditions"]["D0"],
                   "D0_fraction": counts["ucb"]["D0"][g] / protocols["ucb"]["conditions"]["D0"],
                   **{"pooled_"+k: pooled[k] for k in lineage_keys["ucb"]},
                   **{"D0_"+k: d0.get(k, "") for k in next(iter(means["ucb"].values())) if k.startswith("program_")},
                   "D0_score_missing_reason": "" if d0 else "No retained D0 cells in cluster"}
            s15.append(row)
            display.append([g, pname(labels["ucb"][g]), f"{row['n_D0']:,} ({100*row['D0_fraction']:.2f}%)"]+
                           [f"{row['n_'+d]:,}" for d in ORDER["ucb"][1:]]+[f"{row['n_pooled']:,}"])
        assert len(s15) == 16 and sum(r["n_D0"] for r in s15) == 5455
        self.out_csv("s15_tpo_cluster_composition", s15)
        self.table("s15_tpo_cluster_composition", "Complete TPO frozen-cluster composition, including clusters absent at D0. Descriptors are pooled maximum-program labels; Mk denotes megakaryocyte. D0 percentages use all 5,455 retained D0 cells. The two largest D0 clusters (0 and 1) are dendritic-max under the pooled rule. Cluster 5 alone defines the operational root/start subset: its pooled primitive and dendritic means are 0.544 and 0.489, whereas its D0 primitive mean is $-0.263$ among only 17 cells. Thus the pooled label does not imply a primitive-high D0 subset. Different cells are sampled at each day. All pooled lineage scores and all available D0 program means are retained in the CSV; empty D0 scores indicate zero cells, not a zero score.",
                   ["Cluster", "Pooled label", "D0: cells (\\%)", "D4", "D7", "D11", "D14", "Pooled"],
                   [.075, .17, .19, .09, .09, .09, .09, .115], display)

        audit, display, selected = [], [], {}
        program_keys = ["program_"+k for k in protocols["ucb"]["program_genes"]]
        for c in (*COHORTS, "marrow"):
            p = protocols[c]
            relevant = set(p["starts"]) | {x for values in p["ends"].values() for x in values}
            selected[c] = [g for g in labels[c] if labels[c][g] in relevant]
            selected[c].sort(key=(ORDER[c].index if c == "marrow" else int))
            for g in selected[c]:
                label = labels[c][g]
                roles = (["root/start"] if label == p["root"] else []) + [task+" endpoint" for task, endpoints in p["ends"].items() if label in endpoints]
                task_membership = [task+":root/start" for task in p["ends"] if label in p["starts"]] + [task+":endpoint" for task, endpoints in p["ends"].items() if label in endpoints]
                n_by = {d: counts[c].get(d, {}).get(g, 0) for d in ORDER[c]}
                pooled = means[c][g, g] if c == "marrow" else clusters[c][g]
                ranking = top(pooled, lineage_keys[c])
                for scope in ([g] if c == "marrow" else ["pooled", *ORDER[c]]):
                    values = pooled if scope == "pooled" or c == "marrow" else means[c].get((scope, g), {})
                    rank = top(values, lineage_keys[c])
                    n = sum(n_by.values()) if scope == "pooled" else n_by[scope]
                    audit.append({"cohort": c, "group_type": "original_sorted_label" if c == "marrow" else "frozen_leiden_cluster", "group": g,
                                  "frozen_task_label": label, "task_membership": ";".join(task_membership), "scope": scope, "n_cells": n,
                                  "current_scope_max_program": rank[0].removeprefix("program_") if rank else "",
                                  "second_program": rank[1].removeprefix("program_") if len(rank)>1 else "",
                                  "annotation_basis": "original_sorted_population" if c == "marrow" else "pooled_lineage_program_maximum",
                                  "independent_support": "original_sorting_metadata_not_fate_validation" if c == "marrow" else "not_established_by_retained_records",
                                  "program_scores_source": "saved_within_group_program_means" if scope != "pooled" else "saved_cluster_programs",
                                  "missing_score_reason": "no_cells" if n == 0 else "pooled_file_contains_only_lineage_programs" if scope == "pooled" else "",
                                  **{k: values.get(k, "") for k in program_keys}})
                counts_text = f"{sum(n_by.values()):,}" if c == "marrow" else " / ".join(f"{n_by[d]:,}" for d in ORDER[c])
                display.append([LABEL[c]+" / "+g, "; ".join(roles), counts_text,
                                pname(ranking[0])+" ("+f(pooled[ranking[0]])+")",
                                pname(ranking[1])+" ("+f(pooled[ranking[1]])+")"])
            for task, endpoints in p["ends"].items():
                observed_start = sum(sum(counts[c][d].get(g, 0) for d in counts[c]) for g in selected[c] if labels[c][g] in p["starts"])
                observed_end = sum(sum(counts[c][d].get(g, 0) for d in counts[c]) for g in selected[c] if labels[c][g] in endpoints)
                expected = {("ucb", "megakaryocyte"): (2688,17108), ("dapp1", "erythroid"): (3143,87),
                            ("dapp1", "myeloid"): (3143,1839), ("sleep", "myeloid"): (3044,18395),
                            ("marrow", "erythroid"): (1282,1211), ("marrow", "myeloid"): (1282,1012)}[c, task]
                assert (observed_start, observed_end) == expected
                self.checks.append({"name": "complete_start_endpoint_membership", "cohort": c, "task": task,
                                    "start_cells": observed_start, "endpoint_cells": observed_end, "passed": True})
        assert {c: len(v) for c,v in selected.items()} == {"ucb":7,"dapp1":5,"sleep":10,"marrow":3}
        self.out_csv("s16_annotation_audit", audit)
        self.table("s16_annotation_audit", "Every application root/start or endpoint cluster, followed by the separate marrow sorted-label control. Counts are D0/D4/D7/D11/D14 for TPO, WT/KO for Dapp1, CT/SD for sleep, and donor-A totals for marrow. Application labels are operational pooled-program maxima; no independent identity validation was recovered in the inspected records. Highest and second-highest lineage-program means are descriptive competitors, not confidence probabilities. Erythroid/myeloid endpoints retain their frozen membership; myeloid uses granulocytic-max or monocyte-max groups. The CSV supplies every competing lineage score and available non-lineage program for each pooled/condition group, including zero-cell rows. Marrow HSC, MEP and GMP are original sorted labels independent of the scoring rule; their displayed program maxima do not redefine those labels or validate prospective fate.",
                   ["Cohort / group", "Task role", "Cells by condition", "Highest program (mean)", "Second program (mean)"],
                   [.12, .19, .20, .21, .21], display)

        s17, display = [], []
        for c,g in [("ucb","5"), ("dapp1","8")]:
            for r in audit:
                if (r["cohort"],r["group"]) != (c,g):
                    continue
                s17.append(r.copy())
                display.append([LABEL[c]+" / "+g, r["scope"].upper(), f"{r['n_cells']:,}"]+
                               [f(r[k]) for k in ["program_primitive","program_dendritic","program_erythroid","program_mast"]]+
                               [pname(r["current_scope_max_program"])+" ("+f(r["program_"+r["current_scope_max_program"]])+")"])
        assert len(s17) == 9
        wt = next(r for r in s17 if r["cohort"] == "dapp1" and r["scope"] == "wt")
        assert float(wt["program_mast"]) > float(wt["program_erythroid"])
        d0_start = next(r for r in s17 if r["cohort"] == "ucb" and r["scope"] == "D0")
        assert d0_start["n_cells"] == 17 and d0_start["current_scope_max_program"] == "neutrophil"
        self.out_csv("s17_annotation_diagnostics", s17)
        self.table("s17_annotation_diagnostics", "Two visible annotation-dependence flags, with no change to frozen task membership. Scores are copied from saved pooled or condition-by-cluster means; the last column is the maximum among all saved lineage programs, not only the four displayed. TPO cluster 5 is pooled primitive-max but granulocytic-max at D0 (17 cells) and dendritic-max at D14. Dapp1 cluster 8 is pooled erythroid-max but WT mast-max; KO remains erythroid-max. These discrepancies are neither proof of misannotation nor calibrated uncertainty. The companion marker-evidence CSV contains all saved gene means and detection fractions for every audited start/endpoint group, with membership in each scoring program identified. These same-data marker summaries, including markers not in the scoring lists, do not supply independent identity validation. Inspected historical Dapp1 metadata lack biological labels; retained TPO/sleep notebooks contain exploratory gene associations but no independent map to the current clusters. Marrow sorting labels supply separate annotation provenance, not fate validation.",
                   ["Cohort / group", "Scope", "Cells", "Primitive", "Dendritic", "Erythroid", "Mast", "Scope maximum (mean)"],
                   [.12, .09, .09, .12, .12, .12, .10, .16], display)

        markers = []
        for c in (*COHORTS, "marrow"):
            membership = defaultdict(list)
            for program, genes in protocols[c]["program_genes"].items():
                for gene in genes:
                    membership[gene.upper()].append(program)
            for g in selected[c]:
                for d in ORDER[c]:
                    if counts[c].get(d, {}).get(g, 0) == 0:
                        continue
                    values, detection = marker_means[c][d,g], marker_detection[c][d,g]
                    for gene in values:
                        if gene in ["condition", "leiden", "cell_type"]:
                            continue
                        assert 0 <= float(detection[gene]) <= 1
                        markers.append({"cohort": c, "group_type": "original_sorted_label" if c == "marrow" else "frozen_leiden_cluster",
                                        "group": g, "condition": d, "frozen_task_label": labels[c][g], "n_cells": counts[c][d][g],
                                        "gene": gene, "saved_mean_log1p_counts_per_1e4": values[gene], "saved_detection_fraction": detection[gene],
                                        "scoring_program_memberships": ";".join(membership[gene.upper()]),
                                        "evidence_status": "reused_program_marker" if membership[gene.upper()] else "same_data_extra_marker_not_independent_validation"})
        self.out_csv("s17_annotation_marker_evidence", markers)
        self.checks.append({"name": "headline_saved_contrast_recombination", "tolerance": CONTRAST_ABS_TOL, "passed": True, "contrasts": contrasts})
        # Independently cross-check source mapping: weighted condition means must
        # recover every saved pooled lineage mean (float32 output precision).
        worst = 0.0
        for c in COHORTS:
            for g, pooled in clusters[c].items():
                total = sum(counts[c][d][g] for d in ORDER[c])
                for k in lineage_keys[c]:
                    value = math.fsum(counts[c][d][g] * float(means[c][d,g][k]) for d in ORDER[c] if counts[c][d][g]) / total
                    error = abs(value - float(pooled[k])); worst = max(worst, error)
                    assert error <= POOLED_MEAN_ABS_TOL, (c,g,k,error)
        self.checks.append({"name": "all_pooled_lineage_means_match_saved_condition_mapping", "absolute_tolerance": POOLED_MEAN_ABS_TOL,
                            "maximum_absolute_error": worst, "passed": True})
        self.sources["scripts/build_revision_tables.py"] = sha(Path(__file__).read_bytes())
        evidence = {"schema_version":1, "scope":"Saved-table and frozen-label display derivation only; no training, gene-score calculation, annotation reassignment, membership change or biological validation.",
                    "command":"python scripts/build_revision_tables.py --input-root PACKAGE --output-root OUTPUT",
                    "numerical_policy":{"counts_and_identifiers":"exact", "saved_numeric_fields":"verbatim CSV text", "derived_arithmetic":"Python float repr; no rounding in CSV", "pooled_mean_absolute_tolerance":POOLED_MEAN_ABS_TOL, "contrast_absolute_tolerance":CONTRAST_ABS_TOL},
                    "sources_sha256": dict(sorted(self.sources.items())), "outputs_sha256": {k:sha(v) for k,v in sorted(self.outputs.items())},
                    "checks":self.checks, "inspection_record":records, "row_counts":{"s14":len(s14),"s15":len(s15),"s16":len(audit),"s17":len(s17),"marker_evidence":len(markers)}}
        self.outputs["evidence/annotation_revision_manifest.json"] = (json.dumps(evidence,indent=2)+"\n").encode()
        return self.outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-root", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.input_root.resolve()
    out = (args.output_root or root).resolve()
    build = Build(root)
    outputs = build.run()
    for relative, data in outputs.items():
        target = out / relative
        if args.check:
            assert target.read_bytes() == data, f"stale or changed output: {relative}"
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print(json.dumps({"status":"verified" if args.check else "generated", "files":len(outputs), "checks":len(build.checks), "output_root":str(out)},sort_keys=True))


if __name__ == "__main__":
    main()
